export interface PlanetData {
  id: string
  name: string
  /** Visual radius in scene units */
  radius: number
  /** Semi-major axis in scene units (orbital distance scale) */
  orbitRadius: number
  /** Orbital eccentricity (0 = circle) */
  eccentricity?: number
  /** Real semi-major axis in AU (for live metrics) */
  semiMajorAu?: number
  /** Real semi-major axis in km (for live metrics) */
  semiMajorKm?: number
  /** Mean orbital speed km/s (reference) */
  meanOrbitalSpeedKmS?: number
  /** Orbital period in Earth days */
  orbitalPeriod: number
  /** Sidereal rotation period in Earth days (negative = retrograde) */
  rotationPeriod: number
  /** Orbital inclination in degrees */
  inclination: number
  /** Axial tilt in degrees */
  axialTilt: number
  /** Color palette for procedural material */
  color: string
  emissive?: string
  emissiveIntensity?: number
  roughness: number
  metalness: number
  hasRings?: boolean
  hasClouds?: boolean
  isMoon?: boolean
  parentId?: string
  /** Hide from bottom planet list (still selectable via double-click) */
  hideFromList?: boolean
  /** Real scientific data for info panel */
  info: {
    radiusKm: string
    diameterKm: string
    gravity: string
    avgTemp: string
    atmosphere: string
    lengthOfDay: string
    lengthOfYear: string
    moons: string
    distanceFromSun: string
    facts: string[]
  }
}

